const stable = (value) => {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([key, item]) => [key, stable(item)]),
    );
  }
  return value;
};

const pointerValue = (rootValue, pointer) =>
  pointer
    .replace(/^#\//, '')
    .split('/')
    .map((part) => part.replaceAll('~1', '/').replaceAll('~0', '~'))
    .reduce((value, part) => value?.[part], rootValue);

const inlineRefs = (value, rootValue, refs = new Set()) => {
  if (Array.isArray(value)) return value.map((item) => inlineRefs(item, rootValue, refs));
  if (!value || typeof value !== 'object') return value;
  if (typeof value.$ref === 'string' && value.$ref.startsWith('#/')) {
    if (refs.has(value.$ref)) throw new Error(`Recursive schema is not supported: ${value.$ref}`);
    const target = pointerValue(rootValue, value.$ref);
    if (!target) throw new Error(`Unresolved schema reference: ${value.$ref}`);
    return inlineRefs(target, rootValue, new Set([...refs, value.$ref]));
  }
  return Object.fromEntries(
    Object.entries(value).map(([key, item]) => [key, inlineRefs(item, rootValue, refs)]),
  );
};

const definitions = {};

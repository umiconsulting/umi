const nullable = (schema) =>
  schema?.anyOf?.some((item) => item.type === 'null') ||
  (Array.isArray(schema?.type) && schema.type.includes('null'));
const withoutNull = (schema) =>
  schema?.anyOf?.find((item) => item.type !== 'null') ??
  (Array.isArray(schema?.type)
    ? { ...schema, type: schema.type.find((item) => item !== 'null') }
    : schema);

function tsType(input) {
  const schema = withoutNull(input);
  let value = 'unknown';
  if (schema?.enum) value = schema.enum.map((item) => JSON.stringify(item)).join(' | ');
  else if (schema?.type === 'string') value = 'string';
  else if (schema?.type === 'integer' || schema?.type === 'number') value = 'number';
  else if (schema?.type === 'boolean') value = 'boolean';
  else if (schema?.type === 'array') value = `Array<${tsType(schema.items)}>`;
  else if (schema?.type === 'object' && schema.additionalProperties) {
    value = `Record<string, ${tsType(schema.additionalProperties)}>`;
  } else if (schema?.type === 'object') {
    const required = new Set(schema.required ?? []);
    value = `{ ${Object.entries(schema.properties ?? {})
      .map(
        ([key, item]) => `${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${tsType(item)}`,
      )
      .join('; ')} }`;
  }
  return nullable(input) ? `${value} | null` : value;
}


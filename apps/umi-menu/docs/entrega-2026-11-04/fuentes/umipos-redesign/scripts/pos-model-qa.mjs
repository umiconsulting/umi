import assert from 'node:assert/strict'
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import ts from 'typescript'

const dir = await mkdtemp(join(tmpdir(), 'umi-pos-model-'))
try {
  const source = await readFile(new URL('../src/order.ts', import.meta.url), 'utf8')
  await writeFile(join(dir, 'order.mjs'), ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText)
  const m = await import(join(dir, 'order.mjs'))
  assert.equal(typeof m.sendRound, 'function', 'sending must create a round instead of locking the whole account')
  const first = m.sendRound(m.initial)
  const secondDraft = m.addOrderItem(first, m.latte)
  assert.equal(secondDraft.items.length, 3, 'repeat creates a new line')
  assert.equal(secondDraft.items[0].qty, 1, 'already sent quantity stays immutable')
  assert.equal(m.pendingItems(secondDraft).length, 1)
  const second = m.sendRound(secondDraft)
  assert.equal(second.rounds.length, 2)
  assert.equal(second.rounds[0].lineIds.length, 2)
  assert.equal(second.rounds[1].lineIds.length, 1, 'second round sends only the addition')
  assert.equal(m.sendRound(second).rounds.length, 2, 'repeated send is harmless')
  const prepared = { ...second, ...m.stationPatch(second, 'bar', 'preparing', 1) }
  assert.throws(() => m.cancelSentItem(prepared, 'latte', 'duplicate', ''), /autorización/i)
  const cancelled = m.cancelSentItem(prepared, 'latte', 'duplicate', '4826')
  assert.equal(cancelled.items.find(i => i.id === 'latte').voidReason, 'duplicate')
  assert.equal(m.orderTotal(cancelled), 135, 'voided line no longer contributes to charge')
  assert.equal(m.stationItems(cancelled, 'bar', 1).length, 0)

  let s = m.recordPayment(m.initial, { id: 'p1', method: 'Efectivo', channel: 'cash', principal: 50, tip: 5, received: 100 })
  assert.equal(s.paid, false)
  assert.equal(m.balanceDue(s), 85)
  assert.equal(s.payments[0].change, 45)
  assert.equal(m.cashPostings(s)[0].amount, 55, 'cash ledger includes captured cash tip, excludes returned change')
  s = m.recordPayment(s, { id: 'p2', method: 'Transferencia', channel: 'bank', principal: 85, tip: 0, received: 85, reference: 'BANK-DEMO-1' })
  assert.equal(s.paid, false, 'a covered partial ledger still needs account finalization')
  assert.equal(m.balanceDue(s), 0)
  assert.equal(m.finalizePayments(s).paid, true)
  assert.throws(() => m.finalizePayments(m.initial), /saldo/i)
  assert.equal(m.cashPostings(s).length, 1, 'bank transfer does not inflate cash sales')
  assert.equal(m.recordPayment(s, s.payments[1]).payments.length, 2, 'payment id is idempotent')
  assert.throws(() => m.recordPayment(m.initial, { id: 'over', method: 'Efectivo', channel: 'cash', principal: 136, tip: 0, received: 200 }), /saldo/i)
  assert.throws(() => m.recordPayment(m.initial, { id: 'missing', method: 'Transferencia', channel: 'bank', principal: 135, tip: 0, received: 135 }), /folio/i)
  const attempt = m.startTerminal(m.initial, 135, 0)
  assert.throws(() => m.recordPayment(attempt, { id: 'other', method: 'Efectivo', channel: 'cash', principal: 135, tip: 0, received: 200 }), /pendiente/i)
  const unknown = m.terminalOutcome(attempt, 'unknown')
  assert.equal(m.balanceDue(unknown), 135)
  assert.equal(unknown.paid, false)
  assert.throws(() => m.addOrderItem(unknown, m.concha), /pendiente/i)
  const recovered = m.terminalOutcome(unknown, 'approved', 'PROVIDER-DEMO-OK')
  assert.equal(recovered.paid, true)
  assert.equal(m.cashPostings(recovered).length, 0)
  assert.equal(m.terminalOutcome(recovered, 'approved').payments.length, 1)
  const declined = m.terminalOutcome(attempt, 'failed', 'DECLINED')
  assert.equal(m.balanceDue(declined), 135)
  assert.equal(m.recordPayment(declined, { id: 'retry', method: 'Efectivo', channel: 'cash', principal: 135, tip: 0, received: 200 }).paid, true)
  const single = { ...m.demoPaymentPolicy, mixed: false }
  const part = m.recordPayment(m.initial, { id: 'cash1', method: 'Efectivo', channel: 'cash', principal: 50, tip: 0, received: 50 }, single)
  assert.throws(() => m.recordPayment(part, { id: 'card2', method: 'Tarjeta', channel: 'manual', principal: 85, tip: 0, received: 85 }, single), /mismo método/i)
  assert.throws(() => m.adjustItem(part, 'latte', -1), /pagos recibidos/i)
  const part130 = m.recordPayment(m.initial, { id: 'cash130', method: 'Efectivo', channel: 'cash', principal: 130, tip: 0, received: 130 })
  assert.throws(() => m.addOrderItem(part130, { ...m.latte, price: 80, detail: 'Clásico · Entera' }, 'latte'), /pagos recibidos/i)
  assert.throws(() => m.finalizePayments({ ...part, items: [m.concha] }), /saldo/i, 'an inconsistent overpaid account cannot finalize')
  assert.throws(() => m.moveTable(part, 3, 4), /pagos/i)
  assert.throws(() => m.moveTable(unknown, 3, 4), /pendiente/i)
  assert.equal(typeof m.applyCashPostings, 'function', 'cash capture needs a session-wide consumed ID ledger')
  const cash = { status: 'open', owner: 'Ana', opening: 500, sales: 1860, movements: [], counted: null, reason: '', resolved: false, log: [], postedAccounts: [] }
  const posted = m.applyCashPostings(part, cash)
  assert.equal(posted.cashSession.sales, 1910)
  assert.equal(m.applyCashPostings(posted, posted.cashSession), posted, 'posting same captured payment is a no-op')
  const nextShift = { ...posted, cashSession: { ...cash, sales: 0 } }
  assert.equal(m.applyCashPostings(nextShift, nextShift.cashSession).cashSession.sales, 0, 'opening the next shift cannot replay a previous shift payment')
  const parked = m.newAccount({ ...posted, paid: true }, 'takeaway')
  assert.equal(m.applyCashPostings(parked, parked.cashSession).cashSession.sales, 1910, 'switching accounts cannot replay a payment')

  const tables = m.roomOf(m.initial)
  const seated = m.seatTable(m.initial, 2, 4)
  assert.notEqual(seated.account, '042')
  assert.equal(seated.tableNumber, 2)
  const resumed = m.resumeAccount(seated, '042')
  assert.equal(resumed.items.length, 2, 'opening another account preserves original lines')
  assert.equal(resumed.tableNumber, 3)
  const moved = m.moveTable(resumed, 3, 4)
  assert.equal(moved.tableNumber, 4)
  assert.equal(m.roomOf(moved)[4].seatedAt, tables[3].seatedAt)
  assert.equal(m.roomOf(moved)[3].state, 'dirty')
  assert.throws(() => m.moveTable(moved, 4, 1), /ocupada/i)
  const merged = m.mergeTables(m.initial, [2, 4], 6)
  assert.equal(m.roomOf(merged)[2].group, m.roomOf(merged)[4].group)
  const split = m.splitTables(merged, 2)
  assert.equal(m.roomOf(split)[2].guests, 4)
  assert.equal(m.roomOf(split)[4].guests, 2)
  assert.equal(m.roomOf(split)[2].group, undefined)
  assert.equal(m.roomOf(split)[4].group, undefined)
  assert.throws(() => m.mergeTables(m.initial, [1, 2], 4), /ocupada/i)
  assert.throws(() => m.mergeTables(m.initial, [2, 4], 9), /capacidad/i)
  const cleared = m.changeTableState(merged, 2, 'dirty')
  assert.equal(m.roomOf(cleared)[4].state, 'dirty', 'clearing a group clears all members')
  assert.equal(m.changeTableState(cleared, 4, 'open').room[4].state, 'open')
  assert.equal(m.accountList(m.newAccount(m.initial, 'takeaway')).find(a => a.account === '042').items.length, 2)
  assert.equal(typeof m.acceptIncoming, 'function', 'incoming acceptance isolates the previous account state')
  const imported = m.acceptIncoming({ ...first, ...part })
  assert.equal(imported.account, '043')
  assert.equal(m.balanceDue(imported), 135)
  assert.equal(imported.rounds, undefined)
  assert.equal(imported.payments, undefined)
  assert.equal(m.accountList(imported).find(a => a.account === '042').payments[0].principal, 50)
  console.log('PASS POS rounds, immutable fired lines, cancellation approval, partial and mixed payment accounting, terminal uncertainty, table accounts, capacity, movement, group split and cleaning')
} finally { await rm(dir, { recursive: true, force: true }) }

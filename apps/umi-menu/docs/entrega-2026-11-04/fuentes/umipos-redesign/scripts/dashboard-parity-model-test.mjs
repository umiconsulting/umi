import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import ts from 'typescript'

const source = await readFile(new URL('../src/dashboard/parity-model.ts', import.meta.url), 'utf8')
const output = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText
const m = await import(`data:text/javascript;base64,${Buffer.from(output).toString('base64')}`)
const row = (name, cells, values = {}) => ({ name, cells, values })
const orders = [row('A', ['Ana', 'POS', '$80', 'Nuevo']), row('B', ['Luis', 'WhatsApp', '$90', 'Completado']), row('C', ['Sofía', 'POS', '$90', 'Listo'])]
assert.deepEqual(m.filterEntries('orders', orders, '', { Estado: 'Activos', Canal: 'POS' }).map(x => x.name), ['A', 'C'])
assert.deepEqual(m.filterEntries('orders', orders, '', { Estado: 'Completados', Canal: 'WhatsApp' }).map(x => x.name), ['B'])
assert.equal(m.validatePin('123456', '123456'), '')
assert.match(m.validatePin('123', '123'), /4 a 8/)
assert.match(m.validatePin('1234', '1235'), /coincid/)
assert.equal(m.validatePin('', '', true), '')
const routes = [row('Ruta predeterminada', ['Cocina', '0', '15 min', 'Activa']), row('Bebidas', ['Barra', '10', '6 min', 'Activa']), row('Latte', ['Horno', '20', '4 min', 'Activa'])]
assert.equal(m.effectiveRoute('Latte', 'Bebidas', routes).name, 'Latte')
assert.equal(m.effectiveRoute('Americano', 'Bebidas', routes).name, 'Bebidas')
assert.equal(m.effectiveRoute('Latte', 'Bebidas', routes.map(r => r.name === 'Latte' ? { ...r, cells: [...r.cells.slice(0, 3), 'Inactiva'] } : r)).name, 'Bebidas')
assert.equal(m.effectiveRoute('Latte', 'Bebidas', []), null)
assert.match(m.validateChoices([], [{ name: 'Leche', min: 2, max: 1, required: true, options: [{ name: 'Entera', delta: 0, active: true }] }], 80), /selecciones/)
assert.equal(m.validateChoices([{ name: 'Nube', delta: 10, active: true }], [], 80), '')
assert.match(m.validateChoices([{ name: 'Menor', delta: -100, active: true }], [], 80), /precio/)
const person = row('Ana', ['Cajero', 'Centro', 'Habilitado', 'Activa'], { hasPin: 'Sí' })
const noPin = m.applyLocalAction('team', person, 'Quitar PIN', { Motivo: 'Renovación' })
assert.equal(noPin.values.hasPin, 'No')
assert.equal(m.applyLocalAction('team', person, 'Desactivar persona', {}).cells[3], 'Inactiva')
assert.equal(m.applyLocalAction('team', { ...person, cells: ['Cajero', 'Centro', 'Deshabilitado', 'Inactivo'] }, 'Restaurar persona', {}).cells[3], 'Activa')
const client = row('Lucía', ['Hoy', '18', '$2640', 'VIP'], { stamps: '5', balance: '220' })
assert.equal(m.applyLocalAction('customers', client, 'Agregar sellos', { Sellos: '2', 'Referencia del recibo': 'R1' }).values.stamps, '7')
assert.equal(m.applyLocalAction('customers', client, 'Recargar saldo', { Importe: '50' }).values.balance, '270')
const saved = m.safeValues({ 'Nuevo PIN': '123456', 'Confirmar el PIN': '123456', Correo: 'qa@example.com' })
assert.deepEqual(saved, { Correo: 'qa@example.com' })
assert.match(m.validateReceiptLines([{ article: '', quantity: 2, received: 2, price: 10, sku: '' }]), /artículo/)
assert.match(m.validateReceiptLines([{ article: 'Café', quantity: 2, received: 3, price: 10, sku: '' }]), /recibida/)
assert.equal(m.validateReceiptLines([{ article: 'Café', quantity: 2, received: 1, price: 10, sku: 'C1' }]), '')
assert.equal(m.canView('billing', { role: 'Owner', products: ['dashboard'], platform: false }), false)
assert.equal(m.canView('inbox', { role: 'Owner', products: ['dashboard'], platform: true }), false)
assert.equal(m.canView('orders', { role: 'Consulta', products: ['dashboard'], platform: false }), true)
assert.equal(m.canView('team', { role: 'Consulta', products: ['dashboard'], platform: false }), false)
assert.deepEqual(m.receiptDeltas([{ article:'Café', received:6 }], [{ article:'Café', received:4 }]), [{ article:'Café', quantity:2 }])
assert.deepEqual(m.receiptDeltas([{ article:'Café', received:6 }], [{ article:'Café', received:6 }]), [{ article:'Café', quantity:0 }])
m.registerGiftCode('DEMO-ABCDEF','Tarjeta nueva')
const gift = row('Tarjeta nueva',['Cliente','$100','Hoy','Sin canjear'])
assert.equal(await m.giftCardFor('DEMO-ABCDEF',[gift]),gift)
assert.equal(await m.giftCardFor('DEMO-INVALID',[gift]),undefined)
assert.equal(await m.giftCardFor('DEMO-ABCDEF',[{...gift,cells:['Cliente','$100','Hoy','Canjeada']}]),undefined)
const persistedGift={...gift,name:'Tarjeta recargada',values:{codeHash:await m.giftFingerprint('DEMO-PERSIST')}}
assert.equal(await m.giftCardFor('DEMO-PERSIST',[persistedGift]),persistedGift)
console.log('Dashboard parity model: all assertions passed')

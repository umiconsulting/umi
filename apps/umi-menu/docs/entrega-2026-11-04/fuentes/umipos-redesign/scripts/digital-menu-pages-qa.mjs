import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { clickSelectTrigger } from './select-qa.mjs'

const base = process.argv[2] || 'http://localhost:56452'
const browser = await chromium.launch({ executablePath: '/Users/moon/Library/Caches/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-mac-arm64/chrome-headless-shell' })
const page = await browser.newPage({ viewport: {width: 1440, height: 1200} })
page.setDefaultTimeout(15000)
const checks = [], errors = [], missing = []
page.on('pageerror', error => errors.push(error.message))
page.on('response', response => {
  if (response.url().startsWith(base) && response.status() >= 400) missing.push({url:response.url(),status:response.status()})
})
const check = (name, result) => { assert.ok(result, name); checks.push(name); console.log('PASS', name) }
const pickDevice = async name => {
  await clickSelectTrigger(page, page.getByRole('button', {name: /Dispositivo de vista previa/}))
  await page.getByRole('option', {name, exact:true}).click()
  await page.locator('[data-trigger="Select"]').waitFor({state:'detached'})
}
const shot = async name => page.screenshot({path:`shots/digital-menu-pages/${name}.png`,fullPage:true})
try {
  await mkdir('shots/digital-menu-pages', {recursive:true})
  await page.goto(`${base}/?screen=sale`)
  await page.locator('.u-product').first().waitFor()
  await page.getByRole('button', {name:'Menú digital',exact:true}).click()
  check('Sección accesible desde POS y URL compartible', new URL(page.url()).searchParams.get('app') === 'menu')
  const menu = page.frameLocator('iframe[title="Menú digital interactivo"]')
  await menu.locator('.menu-product').first().waitFor()
  await menu.locator('.menu-product img').evaluateAll(async images => {
    await document.fonts.ready
    await Promise.all(images.map(image => image.decode()))
  })
  check('Cuatro destacados con fotos cargadas', await menu.locator('.menu-product img').evaluateAll(images => images.length === 4 && images.every(image => image.complete && image.naturalWidth > 0)))
  check('Enlace completo dentro del mismo sitio', (await page.getByRole('link',{name:'Abrir pantalla completa'}).getAttribute('href')).startsWith('/menu-digital/'))
  await shot('desktop-menu')
  await menu.locator('[data-product=toast]').click()
  await menu.locator('#product-note').fill('Miel aparte')
  await menu.locator('#product-plus').click()
  await pickDevice('iPhone 17 Pro · iOS')
  await menu.locator('#product-dialog[open]').waitFor()
  check('Cambiar dispositivo conserva opciones y cantidad', await menu.locator('#product-note').inputValue() === 'Miel aparte' && await menu.locator('#product-total').textContent() === '$290')
  await pickDevice('PC · Windows')
  await menu.locator('#product-dialog[open]').waitFor()
  await menu.locator('#product-minus').click()
  await menu.locator('#add-to-cart').click()
  await menu.locator('[data-product=latte]').click()
  await menu.locator('#add-to-cart').click()
  check('Carrito interactivo conserva $210', await menu.locator('#mobile-total').textContent() === '$210')
  await page.getByRole('button',{name:'Recorrido por pasos',exact:true}).click()
  const tour = page
  await tour.getByRole('button',{name:'Pausar',exact:true}).click()
  check('Recorrido integrado permite pausa', await tour.getByRole('button',{name:'Reproducir',exact:true}).isVisible())
  await clickSelectTrigger(page,page.getByRole('button',{name:/Velocidad/}))
  await page.getByRole('option',{name:'2×',exact:true}).click()
  await tour.getByRole('button',{name:'Reproducir',exact:true}).click()
  await page.locator('iframe[title="Recorrido del menú digital"]').scrollIntoViewIfNeeded()
  const stage = page.frameLocator('iframe[title="Recorrido del menú digital"]')
  await stage.locator('.ss-stage[data-mark="fin"]').waitFor({timeout:35000})
  const sceneMenu = stage.frameLocator('iframe')
  check('Recorrido alojado llega al carrito de $210', (await sceneMenu.locator('#cart-dialog').innerText()).includes('$210'))
  await tour.getByRole('button',{name:'Repetir escena',exact:true}).click()
  await stage.locator('.ss-stage[data-mark="inicio"]').waitFor()
  checks.push('Repetir reinicia la escena')
  await tour.getByText('Sin animación',{exact:true}).click()
  check('Sin animación responde al control visible',await tour.getByRole('checkbox',{name:'Sin animación'}).isChecked())
  await tour.getByRole('button',{name:'Paso siguiente',exact:true}).click()
  await sceneMenu.locator('#status-dialog[open]').waitFor()
  check('Siguiente abre el envío del pedido', (await sceneMenu.locator('#status-dialog').innerText()).includes('Pedido recibido'))
  await shot('desktop-tour')
  await page.getByRole('button',{name:'Explorar menú',exact:true}).click()
  check('Volver al menú conserva el carrito', await menu.locator('#mobile-total').textContent() === '$210')
  await pickDevice('iPhone 17 Pro · iOS')
  await menu.locator('#mobile-cart-button').click()
  await menu.locator('#cart-dialog [data-checkout]').click()
  await menu.locator('#customer-name').fill('Ana de ejemplo')
  await menu.locator('#customer-phone').fill('6690000000')
  await menu.locator('#confirm-order').click()
  check('Pedido de ejemplo llega a pendiente de aceptación', await menu.locator('#status-dialog-title').textContent() === 'Pedido recibido')
  await page.setViewportSize({width:390,height:1000})
  // Stageshow recalculates its scale in a ResizeObserver after the viewport changes.
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth)
  check('Visor móvil sin desbordamiento', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await shot('mobile-menu')
  await page.getByRole('button',{name:'Recorrido por pasos',exact:true}).click()
  await clickSelectTrigger(page,page.getByRole('button',{name:/Capítulo del recorrido/}))
  await page.getByRole('option',{name:'02 · Elegir productos',exact:true}).click()
  if(!await tour.getByRole('checkbox',{name:'Sin animación',exact:true}).isChecked())await tour.getByText('Sin animación',{exact:true}).click()
  await stage.locator('.ss-stage[data-layout="compact"]').waitFor()
  await sceneMenu.locator('#cart-dialog[open]').waitFor()
  check('Recorrido móvil muestra el carrito', (await sceneMenu.locator('#cart-dialog').innerText()).includes('$210'))
  await shot('mobile-tour')
  await page.goto(`${base}/?app=menu&menuView=tour`)
  await tour.getByRole('button',{name:'Pausar',exact:true}).waitFor()
  check('Enlace directo abre el recorrido', await page.getByRole('button',{name:'Recorrido por pasos',exact:true}).getAttribute('aria-pressed') === 'true')
  await page.getByRole('button',{name:'Dashboard',exact:true}).click()
  await page.locator('.d-app').waitFor()
  check('Dashboard sigue accesible desde la sección nueva', await page.locator('.d-app').isVisible())
  await page.goto(`${base}/menu-digital/menu.html`)
  await page.locator('.menu-product').first().waitFor()
  check('Menú independiente disponible', await page.locator('.menu-product').count() === 4)
  await page.goto(`${base}/menu-digital/recorrido/index.html?chapter=menu&mode=pickup`)
  await page.getByRole('link',{name:'Volver al visor'}).waitFor()
  check('Recorrido independiente usa el mismo visor del redesign',await page.locator('.menu-flow-show').isVisible()&&new URL(page.url()).searchParams.has('menuFullscreen'))
  check('Sin recursos faltantes ni errores de página', errors.length === 0 && missing.length === 0)
  await writeFile('shots/digital-menu-pages/qa.json',JSON.stringify({base,checks,errors,missing},null,2))
} catch (error) {
  await shot('failure').catch(()=>{})
  await writeFile('shots/digital-menu-pages/qa.json',JSON.stringify({base,checks,errors,missing,failure:String(error)},null,2))
  throw error
} finally { await browser.close() }
